import type { SiteSettings } from "@/types/site-settings";
import {
  getLegalDetails,
  getPrivacyContactEmail,
  hasCompleteLegalDetails,
} from "@/lib/site-settings/mapper";

type LegalSection = {
  title: string;
  paragraphs: string[];
  list?: string[];
};

export function buildPrivacySections(settings: SiteSettings): LegalSection[] {
  const operatorName = settings.legalName || settings.companyName;
  const privacyEmail = getPrivacyContactEmail(settings);
  const details = getLegalDetails(settings);
  const complete = hasCompleteLegalDetails(settings);

  const operatorLines: string[] = [
    `Оператором персональных данных является ${operatorName} (бренд: ${settings.companyName}).`,
  ];

  if (details.length > 0) {
    operatorLines.push(
      "Известные реквизиты оператора:",
      ...details.map((row) => `${row.label}: ${row.value}`)
    );
  } else {
    operatorLines.push(
      "Реквизиты оператора будут опубликованы на этой странице после заполнения в настройках сайта. До публикации реквизитов обращение по вопросам персональных данных можно направить через страницу «Контакты»."
    );
  }

  if (privacyEmail) {
    operatorLines.push(
      `Электронная почта для обращений по персональным данным: ${privacyEmail}.`
    );
  }

  if (!complete && process.env.NODE_ENV !== "production") {
    // Developer-only note is NOT rendered on the public page.
  }

  return [
    {
      title: "1. Общие положения",
      paragraphs: [
        "Настоящая Политика определяет порядок обработки и защиты персональных данных пользователей сайта MBN Строй, связанных с подачей заявок на консультацию и предварительную оценку ремонта.",
        "Используя сайт и отправляя форму заявки, пользователь подтверждает, что ознакомлен с настоящей Политикой.",
      ],
    },
    {
      title: "2. Основные понятия",
      paragraphs: [
        "Персональные данные — любая информация, относящаяся прямо или косвенно к определённому или определяемому физическому лицу.",
        "Обработка персональных данных — любое действие или совокупность действий с персональными данными, включая сбор, запись, систематизацию, хранение, уточнение, использование, передачу, обезличивание, блокирование, удаление и уничтожение.",
        "Оператор — лицо, самостоятельно или совместно с другими лицами организующее и (или) осуществляющее обработку персональных данных.",
      ],
    },
    {
      title: "3. Оператор",
      paragraphs: operatorLines,
    },
    {
      title: "4. Какие персональные данные обрабатываются",
      paragraphs: [
        "Сайт обрабатывает только данные, которые пользователь добровольно указывает в формах заявки, а также технические сведения, необходимые для работы и защиты формы.",
      ],
      list: [
        "имя — если указано;",
        "телефон — если указан;",
        "email — если указан;",
        "комментарий пользователя;",
        "параметры калькулятора (если заявка отправлена после расчёта);",
        "контекст страницы заявки (например, проект или услуга);",
        "дата и время отправки заявки;",
        "технические данные, необходимые для работы и защиты формы (в том числе признаки антиспам-проверок).",
      ],
    },
    {
      title: "5. Цели обработки",
      paragraphs: [
        "Персональные данные обрабатываются для обработки обращения пользователя, связи с пользователем, уточнения параметров ремонта, подготовки предварительной оценки и обсуждения услуг.",
        "Оператор не использует указанные данные для рекламных рассылок.",
      ],
    },
    {
      title: "6. Правовые основания",
      paragraphs: [
        "Обработка осуществляется на основании согласия субъекта персональных данных, выраженного при отправке формы заявки, а также в случаях, предусмотренных законодательством Российской Федерации.",
      ],
    },
    {
      title: "7. Способы обработки",
      paragraphs: [
        "Обработка выполняется с использованием средств автоматизации и без использования таких средств: сбор через формы сайта, запись в информационную систему оператора, хранение, использование для связи по заявке, обновление статуса заявки, удаление или обезличивание по истечении срока либо по обращению субъекта.",
      ],
    },
    {
      title: "8. Сроки обработки и хранения",
      paragraphs: [
        "Персональные данные обрабатываются в течение срока, необходимого для рассмотрения заявки и последующей коммуникации по ней, а также в сроки, установленные законодательством Российской Федерации.",
        "По достижении целей обработки или при отзыве согласия данные подлежат удалению либо обезличиванию, если иное не предусмотрено законодательством.",
      ],
    },
    {
      title: "9. Передача и доступ к данным",
      paragraphs: [
        "Доступ к заявкам имеют уполномоченные сотрудники (представители) оператора, которым он необходим для обработки обращений.",
        "Передача третьим лицам возможна только в случаях, предусмотренных законодательством, либо при наличии законного основания и необходимости для исполнения запроса пользователя (например, привлечение подрядчиков к обсуждению задачи — только в объёме, необходимом для обработки обращения).",
      ],
    },
    {
      title: "10. Защита персональных данных",
      paragraphs: [
        "Оператор принимает организационные и технические меры, направленные на защиту персональных данных от неправомерного доступа, уничтожения, изменения, блокирования, копирования, распространения и иных неправомерных действий.",
      ],
    },
    {
      title: "11. Права субъекта",
      paragraphs: [
        "Субъект персональных данных вправе получать сведения об обработке своих данных, требовать уточнения, блокирования или уничтожения данных при наличии оснований, предусмотренных законодательством, а также отозвать согласие на обработку.",
      ],
    },
    {
      title: "12. Отзыв согласия",
      paragraphs: [
        "Согласие на обработку персональных данных может быть отозвано путём направления обращения оператору. После получения отзыва обработка прекращается, за исключением случаев, когда обработка допускается без согласия на основаниях, предусмотренных законодательством.",
      ],
    },
    {
      title: "13. Обращение к оператору",
      paragraphs: [
        privacyEmail
          ? `По вопросам обработки персональных данных можно обратиться по адресу: ${privacyEmail}, либо через страницу «Контакты» на сайте.`
          : "По вопросам обработки персональных данных можно обратиться через страницу «Контакты» на сайте.",
      ],
    },
    {
      title: "14. Изменение политики",
      paragraphs: [
        "Оператор может обновлять настоящую Политику. Актуальная редакция публикуется на этой странице. Рекомендуется периодически знакомиться с её содержанием.",
      ],
    },
  ];
}

export function buildConsentSections(settings: SiteSettings): LegalSection[] {
  const operatorName = settings.legalName || settings.companyName;
  const privacyEmail = getPrivacyContactEmail(settings);

  return [
    {
      title: "1. Предмет согласия",
      paragraphs: [
        `Настоящим я даю ${operatorName} (бренд: ${settings.companyName}) согласие на обработку персональных данных, указанных мной при отправке заявки на сайте.`,
      ],
    },
    {
      title: "2. Состав данных",
      paragraphs: [
        "Согласие распространяется на следующие данные в том объёме, в котором они были мной предоставлены:",
      ],
      list: [
        "имя;",
        "телефон;",
        "email;",
        "комментарий;",
        "параметры расчёта стоимости ремонта (если заявка отправлена после использования калькулятора);",
        "контекст страницы, с которой отправлена заявка.",
      ],
    },
    {
      title: "3. Цели обработки",
      paragraphs: [
        "Данные обрабатываются для обработки заявки, обратной связи и уточнения задачи по ремонту.",
        "Согласие не включает направление рекламных рассылок.",
      ],
    },
    {
      title: "4. Действия с данными",
      paragraphs: [
        "Согласие включает совершение действий, необходимых для указанных целей: сбор, запись, систематизацию, хранение, уточнение, использование, передачу уполномоченным лицам оператора, блокирование, удаление и уничтожение.",
      ],
    },
    {
      title: "5. Срок и отзыв",
      paragraphs: [
        "Согласие действует до достижения целей обработки либо до его отзыва.",
        privacyEmail
          ? `Отозвать согласие можно, направив обращение на ${privacyEmail} или через страницу «Контакты».`
          : "Отозвать согласие можно, направив обращение через страницу «Контакты».",
      ],
    },
    {
      title: "6. Подтверждение",
      paragraphs: [
        "Отмечая соответствующее поле в форме заявки и отправляя форму, я подтверждаю, что ознакомлен с Политикой в отношении обработки персональных данных и даю согласие на указанных условиях.",
      ],
    },
  ];
}
